import { assertStagedChangeIsSafe } from './commit-guard';
import { GitError, type GitRunner } from './git-runner';

export class CommitMessageError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'CommitMessageError';
  }
}

/** The push was rejected or failed. The ticket goes on hold (`needs_help`, BUILD_PLAN 6.8); pushes are never forced. */
export class PushRejectedError extends Error {
  constructor(
    message: string,
    readonly branch: string,
  ) {
    super(message);
    this.name = 'PushRejectedError';
  }
}

export interface GitIdentity {
  name: string;
  email: string;
}

/** Attribution that must never appear in a commit message (F9): trailers and "generated by" lines. */
const ATTRIBUTION: readonly [RegExp, string][] = [
  [/^\s*co-authored-by:/im, 'a Co-Authored-By trailer'],
  [/generated (with|by)\b/i, 'a "generated with/by" line'],
  [/🤖/u, 'a robot emoji attribution'],
  [/noreply@anthropic\.com/i, 'an Anthropic address'],
];

export function assertCommitMessage(message: string): void {
  if (message.trim() === '') throw new CommitMessageError('The commit message is empty');
  for (const [pattern, what] of ATTRIBUTION) {
    if (pattern.test(message)) throw new CommitMessageError(`The commit message contains ${what}; commits carry no AI attribution`);
  }
}

export type CommitResult = { committed: false } | { committed: true; sha: string };

/**
 * Stages everything and commits it as the configured identity (BUILD_PLAN 6.2). Repository hooks never run
 * (`core.hooksPath=/dev/null`) and the commit uses `--no-verify`. Returns `committed: false` when nothing changed.
 */
export async function commitAll(git: GitRunner, workspace: string, message: string, identity: GitIdentity, opts: { paths?: readonly string[] } = {}): Promise<CommitResult> {
  assertCommitMessage(message);
  if (!identity.name.trim() || !identity.email.trim()) throw new Error('GIT_AUTHOR_NAME and GIT_AUTHOR_EMAIL must be set to commit');

  // `paths` limits what is staged (the KB commit stages only the KB directory); the default stages everything.
  await git.run(['add', '-A', ...(opts.paths && opts.paths.length > 0 ? ['--', ...opts.paths] : [])], { cwd: workspace });
  if ((await git.out(['diff', '--cached', '--name-only'], { cwd: workspace })) === '') return { committed: false };
  await assertStagedChangeIsSafe(git, workspace); // node_modules, .env*, keys and files over 1 MB fail the stage

  await git.run(['commit', '--no-verify', '-m', message], {
    cwd: workspace,
    env: { GIT_AUTHOR_NAME: identity.name, GIT_AUTHOR_EMAIL: identity.email, GIT_COMMITTER_NAME: identity.name, GIT_COMMITTER_EMAIL: identity.email },
  });
  return { committed: true, sha: await git.out(['rev-parse', 'HEAD'], { cwd: workspace }) };
}

const PUSH_URL_PREFIX = 'https://github.com/';

/**
 * Pushes the ticket branch to the project's stored repository URL, never to the workspace's `origin` (an agent can edit
 * the workspace git config). Never forced: no `--force`, no `+` refspec. `allowedUrlPrefixes` is only widened by tests.
 */
export async function pushBranch(git: GitRunner, workspace: string, branch: string, repoUrl: string, allowedUrlPrefixes: readonly string[] = [PUSH_URL_PREFIX]): Promise<void> {
  if (!branch || branch.startsWith('+') || branch.startsWith('-')) throw new Error(`Refusing to push "${branch}"`);
  if (!allowedUrlPrefixes.some((prefix) => repoUrl.startsWith(prefix))) throw new Error('Refusing to push: the repository URL is not a github.com URL');
  try {
    await git.run(['push', repoUrl, `refs/heads/${branch}:refs/heads/${branch}`], { cwd: workspace });
  } catch (err) {
    if (err instanceof GitError) throw new PushRejectedError(`Push of ${branch} was rejected: ${err.message}`, branch);
    throw err;
  }
}
